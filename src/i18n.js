let currentLang = 'en';

export function getLang() {
  return currentLang;
}

export function setLangState(lang) {
  currentLang = lang === 'km' ? 'km' : 'en';
}

export function t(key, opts = {}) {
  const s =
    (translations[currentLang] && translations[currentLang][key]) ||
    translations.en[key] ||
    key;
  if (typeof s !== 'string') return key;
  const numValues =
    opts.values ||
    (opts.applied !== undefined && opts.failed !== undefined
      ? [opts.applied, opts.failed]
      : null);
  let numIndex = 0;
  return s
    .replace(/%s/g, () => opts.s ?? opts.name ?? '')
    .replace(/%d/g, () =>
      String(numValues ? (numValues[numIndex++] ?? 0) : (opts.d ?? opts.count ?? 0)),
    );
}

export function applyDomTranslations() {
  document.documentElement.lang = currentLang === 'km' ? 'km' : 'en';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
  document.querySelectorAll('.lang-btn').forEach((b) => {
    b.classList.toggle('active', b.dataset.lang === currentLang);
  });
}
